        const ICON_BYTES: &[u8] = &[0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x20, 0x20, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x84, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x20, 0x08, 0x06, 0x00, 0x00, 0x00, 0x73, 0x7a, 0x7a, 0xf4, 0x00, 0x00, 0x00, 0x4b, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0x63, 0x10, 0x14, 0x91, 0xfd, 0x3f, 0x90, 0x98, 0x61, 0xd4, 0x01, 0xa3, 0x0e, 0xc0, 0x26, 0xb8, 0xed, 0x73, 0x36, 0x4d, 0xf0, 0xa8, 0x03, 0x46, 0x1d, 0x40, 0x91, 0x03, 0x44, 0x64, 0x78, 0x29, 0xc2, 0xa3, 0x0e, 0x18, 0x7e, 0x0e, 0x20, 0x94, 0xe0, 0x46, 0x1d, 0x30, 0xfc, 0x1d, 0x30, 0x9a, 0x0b, 0x46, 0x9e, 0x03, 0x46, 0x6b, 0xc3, 0x51, 0x07, 0xd0, 0xd5, 0x01, 0xa3, 0xfd, 0x82, 0x51, 0x07, 0xd0, 0x13, 0x03, 0x00, 0xdb, 0x1e, 0x4f, 0x12, 0xc9, 0xfd, 0x83, 0xf9, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82];
